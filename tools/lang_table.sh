#!/bin/bash
# lang_table.sh <build folder> [lang/<code>.po ...]: the interface's
# translations as C (stdout), for source/core/Lang.cpp: each .po compiled
# by msgfmt (big-endian, like the Wii; -c refuses a translation whose %d / %s
# differ from the English), then its bytes and a table of the languages.
set -e
B=$1; shift
echo '/* generated by tools/lang_table.sh from lang/<code>.po */'
echo 'struct LangMo { const char* code; const unsigned char* data; unsigned size; };'
codes=()
for po in "$@"; do
    c=$(basename "$po" .po)
    msgfmt -c --endianness=big -o "$B/lang_$c.mo" "$po"
    # not const: .data, which the link puts with the other blobs (wii_wiifin.ld)
    xxd -i -n "lang_${c}_mo" "$B/lang_$c.mo" | sed '/_len =/d; s/^unsigned/static unsigned/'
    codes+=("$c")
done
echo 'const struct LangMo g_lang_mo[] = {'
for c in "${codes[@]}"; do echo "    { \"$c\", lang_${c}_mo, sizeof lang_${c}_mo },"; done
[ ${#codes[@]} -gt 0 ] || echo '    { 0, 0, 0 },'
echo '};'
echo "const int g_lang_mo_count = ${#codes[@]};"
